// Level data for the Wolfenstein-style FPS. Pure data: no three.js, no DOM.
//
// This file is the single source of truth for the map grid, the spawn tables,
// the door-lock table, the wall-material table, and the tile scale every later
// spec reads. It is authored in-file as a string array (FR-001) and is an
// original hand-designed grid maze in the spirit of E1M1 — right angles, locked
// doors, secrets and an elevator exit — not id Software's layout (FR-002).

// Tile scale, fixed here for the whole project (FR-006). 003's collider and
// 004's door travel read these constants rather than re-declaring them.
export const TILE_SIZE = 1;
export const FLOOR_Y = 0;
export const CEILING_Y = 2;

export const GRID_SIZE = 64;

export interface TileCoord {
  x: number;
  z: number;
}

export interface PlayerSpawn {
  x: number;
  z: number;
  /** Facing yaw in radians around the Y axis; 0 faces -Z (three.js forward). */
  yaw: number;
}

export type ItemKind = 'health' | 'ammo' | 'treasure' | 'silver-key' | 'gold-key';

export interface ItemSpawn {
  x: number;
  z: number;
  kind: ItemKind;
}

export type LockKind = 'none' | 'silver' | 'gold';

export interface WallMaterial {
  name: string;
  color: number;
}

